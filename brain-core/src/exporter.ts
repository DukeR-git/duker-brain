/**
 * Universal Rules Exporter (brain export).
 *
 * Translates an Obsidian brain vault into rules and configuration formats
 * for external coding assistants: Cursor (.cursor/rules/*.mdc), Windsurf (.windsurfrules),
 * Aider (.aider.conf.yml), and clean markdown bundles.
 */

import { existsSync, mkdirSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

import { splitFrontmatter } from "./frontmatter.js";
import { writeFileAtomic } from "./fsutil.js";
import { scanVault } from "./vault.js";
import type { ExportFormat, ExportOptions, ExportResult, VaultNode } from "./types.js";

/** Every exported file carries this, so a later export knows which files it may replace. */
export const GENERATED_MARKER = "Generated by brain-keeper export";

interface CollectedNote {
	id: string;
	title: string;
	criteria: string;
	path: string;
	absolutePath: string;
	body: string;
	globs?: string;
}

/**
 * Exports vault notes to the specified target assistant format.
 */
export async function exportVault(
	vaultRoot: string,
	format: ExportFormat,
	outDir: string,
	options: ExportOptions = {},
): Promise<ExportResult> {
	const tree = scanVault(vaultRoot);
	const notes: CollectedNote[] = [];

	function collectLeaves(node: VaultNode) {
		if (node.kind === "leaf") {
			try {
				const raw = readFileSync(node.absolutePath, "utf8");
				const parsed = splitFrontmatter(raw);
				notes.push({
					id: node.id,
					title: node.title || node.id,
					criteria: node.criteria,
					path: node.path,
					absolutePath: node.absolutePath,
					body: parsed.body.trim(),
				});
			} catch {
				// Skip unreadable files
			}
		} else if (node.children) {
			for (const child of node.children) {
				collectLeaves(child);
			}
		}
	}

	collectLeaves(tree.root);

	const resolvedOutDir = resolve(outDir);
	// Every file is planned first, so a refused overwrite leaves nothing half-exported.
	const planned: { path: string; content: string }[] = [];

	switch (format) {
		case "cursor": {
			// One .mdc per note, named by id; an id two folders share gets its folder path too.
			const ids = new Map<string, number>();
			for (const note of notes) ids.set(note.id, (ids.get(note.id) ?? 0) + 1);
			for (const note of notes) {
				const name = ids.get(note.id)! > 1 ? note.path.replace(/\.md$/i, "").replace(/[\\/]/g, "__") : note.id;
				planned.push({ path: join(resolvedOutDir, `${name}.mdc`), content: renderCursorMdc(note) });
			}
			break;
		}

		case "windsurf": {
			const targetFile = resolvedOutDir.endsWith(".windsurfrules")
				? resolvedOutDir
				: join(resolvedOutDir, ".windsurfrules");
			planned.push({ path: targetFile, content: renderWindsurfRules(notes) });
			break;
		}

		case "aider": {
			// .aider.conf.yml plus clean copies of the notes in .brain-docs/
			for (const note of notes) {
				planned.push({ path: join(resolvedOutDir, ".brain-docs", note.path), content: renderPlainNote(note) });
			}
			const aiderConfig = [
				`# ${GENERATED_MARKER} from a brain-traverse vault`,
				"read:",
				...notes.map((note) => `  - .brain-docs/${note.path.replace(/\\/g, "/")}`),
				"",
			].join("\n");
			planned.push({ path: join(resolvedOutDir, ".aider.conf.yml"), content: aiderConfig });
			break;
		}

		case "bundle": {
			// Clean markdown copies with a README.md table of contents
			for (const note of notes) {
				planned.push({ path: join(resolvedOutDir, note.path), content: renderPlainNote(note) });
			}
			const indexLines = [
				"# Reference Guides Index",
				"",
				`${GENERATED_MARKER} from the knowledge vault.`,
				"",
				"| Document | Criteria / Scope |",
				"|---|---|",
				...notes.map((n) => `| [${n.title}](${n.path.replace(/\\/g, "/")}) | ${n.criteria} |`),
				"",
			];
			planned.push({ path: join(resolvedOutDir, "README.md"), content: indexLines.join("\n") });
			break;
		}
	}

	// Never replace a file this exporter did not write (a hand-made .aider.conf.yml, say) unless asked to.
	const foreign = options.overwrite
		? []
		: planned.filter(({ path }) => existsSync(path) && !readFileSync(path, "utf8").includes(GENERATED_MARKER));
	if (foreign.length) {
		throw new Error(
			`these files already exist and were not written by brain-keeper export: ${foreign.map(({ path }) => path).join(", ")}. ` +
				"Move them away, choose another output folder, or pass overwrite to replace them.",
		);
	}

	if (!options.dryRun) {
		for (const { path, content } of planned) {
			mkdirSync(dirname(path), { recursive: true });
			writeFileAtomic(path, content);
		}
	}

	return {
		format,
		outDir: resolvedOutDir,
		filesWritten: planned.map(({ path }) => path),
		noteCount: notes.length,
		dryRun: Boolean(options.dryRun),
	};
}

function renderCursorMdc(note: CollectedNote): string {
	const globs = deriveGlobs(note.path);
	return [
		"---",
		`description: ${note.title} - ${note.criteria}`,
		`globs: ${globs}`,
		"alwaysApply: false",
		"---",
		`<!-- ${GENERATED_MARKER} -->`,
		`# ${note.title}`,
		"",
		note.body,
		"",
	].join("\n");
}

function renderPlainNote(note: CollectedNote): string {
	return `<!-- ${GENERATED_MARKER} -->\n# ${note.title}\n\n${note.body}\n`;
}

function renderWindsurfRules(notes: CollectedNote[]): string {
	const sections: string[] = [
		"# Reference Rules & Architecture Guidelines",
		"",
		`<!-- ${GENERATED_MARKER} -->`,
		"",
	];

	for (const note of notes) {
		sections.push(`## ${note.title} (${note.id})`);
		sections.push(`> **Criteria**: ${note.criteria}`);
		sections.push("");
		sections.push(note.body);
		sections.push("");
		sections.push("---");
		sections.push("");
	}

	return sections.join("\n");
}

function deriveGlobs(relPath: string): string {
	const lower = relPath.toLowerCase().replace(/\\/g, "/");
	if (lower.includes("backend")) {
		return "**/*.py, **/*.ts, **/*.js, **/*.go, **/*.rs";
	}
	if (lower.includes("frontend")) {
		return "**/*.tsx, **/*.jsx, **/*.vue, **/*.svelte, **/*.css, **/*.html";
	}
	if (lower.includes("infra") || lower.includes("docker") || lower.includes("deploy")) {
		return "**/Dockerfile*, **/docker-compose*, **/*.yaml, **/*.yml,**/*.sh";
	}
	return "**/*";
}
